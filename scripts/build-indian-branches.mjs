/** Authored display connections, not shipping services or surveyed cables.
 * Coastal endpoints are reused verbatim from the existing derived atlas. */
import {readFileSync,writeFileSync} from 'node:fs';
import {registerHooks} from 'node:module';
registerHooks({resolve(s,c,n){return n(c.parentURL?.includes('/lib/')&&s.startsWith('.')&&!s.endsWith('.ts')?s+'.ts':s,c)}});
const {marinePath,sampleMarinePath}=await import('../lib/world/marine-path.ts');
const {sampleElevation}=await import('../lib/terra/spatial.ts');
const {schematicPassage}=await import('../lib/world/ocean-geography.ts');
const b=readFileSync('public/data/relief-grid.bin'),grid=new Int16Array(b.buffer,b.byteOffset,b.byteLength/2);
const source=JSON.parse(readFileSync('public/data/networks/marine-branches.json'));
const anchor=name=>source.sea.find(p=>p.label.startsWith(name+' offshore')).waypoints[0];
const origins=[
 ['Dar es Salaam',[[-7.5,42],[-5,47]]],
 ['Durban',[[-30.5,33],[-23,36],[-16,42],[-10,43],[-5,47]]],
 ['Maputo',[[-26.5,35.5],[-24,36.5],[-19,39.5],[-16,42],[-12,43],[-7,44],[-5,47]]],
 ['Port Elizabeth',[[-35,28],[-33,32],[-25,35.5],[-17,42],[-10,43],[-5,47]]],
];
const destinations=[
 ['Kochi',[[3,73],[5.5,75],[8,75.4]]],
 ['Chennai',[[3,76],[4.2,80],[6,82.2],[10,82.2]]],
 ['Medan',[[1.5,76],[3.2,85],[6.1,93],[6.1,95.4],[5.55,97.3],[4.375,99.125]]],
 ['Perth',[]],
];
const sea=[];
for(const [i,[from,coast]] of origins.entries())for(const [j,[to,approach]] of destinations.entries()){
 const ocean=to==='Perth'?[[from==='Dar es Salaam'?-9:-34,from==='Dar es Salaam'?44:36],[-34,51],[-36-i*.65,72],[-35-i*.35,93],[-33.2,110],[-33.2,115]]:[...coast,[-2+i*.3,53],[.5+i*.25,64],...approach];
 // Northern Madagascar must be rounded before a Dar es Salaam–Perth crossing.
 if(to==='Perth'&&from==='Dar es Salaam')ocean.splice(0,2,[-7.5,42],[-9,45],[-10,50],[-17,57],[-28,65]);
 const waypoints=[anchor(from),...ocean,anchor(to)],id='indian-feeder-'+i+'-'+j;
 const path=marinePath(id,from+' / '+to,waypoints,0,1.002),out=new Float64Array(3);
 for(let k=0;k<=Math.ceil(path.totalArc/.0002);k++){
  sampleMarinePath(path,k/Math.ceil(path.totalArc/.0002),out);
  const lat=Math.atan2(out[1],Math.hypot(out[0],out[2]))*180/Math.PI,lon=Math.atan2(out[0],out[2])*180/Math.PI;
  if(sampleElevation(grid,1440,720,lon,lat)>=-5&&!schematicPassage(lon,lat))throw new Error(id+' leaves water at '+lat+','+lon);
 }
 sea.push({id,label:from+' offshore / '+to+' offshore',waypoints,tier:'regional',intensity:.64+((i+j)%3)*.08});
}
const payload={provenance:'Illustrative Indian Ocean connections. Existing Natural Earth-derived offshore anchors; authored water-checked approaches. Not measured shipping routes, surveyed cables or live traffic.',prepared:'2026-09-18',source:'marine-branches.json coastal anchors; NOAA ETOPO relief-grid.bin',sea,cables:sea.map(p=>({...p,id:'cable-'+p.id,intensity:p.intensity*.84}))};
writeFileSync('public/data/networks/indian-branches.json',JSON.stringify(payload));
writeFileSync('lib/world/indian-network-data.ts','/** Generated by scripts/build-indian-branches.mjs. Illustrative, not measured routes. */\nimport type { MarineRow } from \"./connection-atlas\";\nexport const indianBranches: {provenance:string;prepared:string;source:string;sea:MarineRow[];cables:MarineRow[]} = '+JSON.stringify(payload)+';\n');
console.log(JSON.stringify({result:'PASS',sea:sea.length,cables:sea.length,waterStepRadians:.0002}));
